// build-preview-data.mjs
//
// Creates .preview-data/ by cloning data/ and injecting sample editorial
// fields (editorial.overall_en/zh, editorial.cuts) into claude-summaries.json
// so `npm run preview:demo` shows what Editor's Cut commentary boxes look
// like before the GHA cron populates the real fields.
//
// Demo only. Real editorial data is produced by the routine prompt extension
// in production via the GHA fetch-sources.yml workflow.

import { mkdir, readdir, copyFile, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { articleId } from "./lib/article-id.mjs";

const SRC = "data";
const DST = ".preview-data";

async function copyDir(src, dst) {
  await mkdir(dst, { recursive: true });
  const entries = await readdir(src, { withFileTypes: true });
  for (const e of entries) {
    const srcPath = join(src, e.name);
    const dstPath = join(dst, e.name);
    if (e.isFile()) await copyFile(srcPath, dstPath);
    else if (e.isDirectory()) await copyDir(srcPath, dstPath);
  }
}

await copyDir(SRC, DST);

// Read the four aihot data files for the main items — pick first 3 with
// URLs from across them to use as demo cuts. The renderer feeds these into
// the aihotItemsCard sections (models/products/industry/papers) and computes
// article_id via articleId(item.source, item.url) — same formula here.
const sources = [
  "aihot-ai-models.json",
  "aihot-ai-products.json",
  "aihot-industry.json",
  "aihot-paper.json",
];
const allItems = [];
for (const fname of sources) {
  const j = JSON.parse(
    await readFile(join(DST, fname), "utf-8").catch(() => "{}"),
  );
  if (Array.isArray(j?.items)) allItems.push(...j.items);
}
const cuts = allItems
  .filter((it) => it && it.url)
  .slice(0, 3)
  .map((it, i) => ({
    article_id: articleId(it.source || "src", it.url),
    commentary_en: [
      "Demo commentary: this is what the routine's per-cut Editor's Cut note will look like once the GHA cron runs with the new prompt extension. The real version is 30–50 words of editorial voice on why this article matters.",
      "Demo commentary: a second sample — the spec calls for 8 to 15 cuts per digest, each ~30-50 words. Bilingual EN+ZH written natively in the same routine pass.",
      "Demo commentary: third sample for preview purposes. Production version is generated by the extended routine prompt against a real article body and digest context.",
    ][i],
    commentary_zh: [
      "示例评论：这是日常摘要使用扩展提示词运行后，每篇精选文章下方将出现的“为何值得关注”编辑评论。正式版本约 30-50 字。",
      "示例评论：第二个示例。规范要求每日精选 8-15 篇，每篇双语原生 30-50 字。",
      "示例评论：第三个示例，仅用于预览。生产版本将由扩展后的提示词针对真实文章正文与当日上下文生成。",
    ][i],
  }));

const cs = JSON.parse(
  await readFile(join(DST, "claude-summaries.json"), "utf-8"),
);

cs.editorial = {
  overall_en:
    "Demo overall editorial — this paragraph (200-300 words in production) is the daily narrative for the email newsletter. The routine will write what these stories add up to, in a knowledgeable but human voice. Today's digest spans local LLM benchmarks, AMD Strix Halo throughput numbers, a community megakernel rediscovery, an open-source MOL-MOACT2 robotics line, and assorted workflow shifts. The real Editor's Cut narrative will frame these as a single thread rather than a list — what they mean, where they're heading, and why the reader should care this week rather than next.",
  overall_zh:
    "示例总编辑评论 —— 该段落（正式版约 200-300 字）将作为每日邮件简报的主体叙述。正式版本将以见识与人情味兼具的口吻，串联当日要闻。今日内容涵盖本地大模型基准、AMD Strix Halo 的吞吐数据、社区对 megakernel 的再发现、Allen AI 的 MolmoAct2 开源机器人模型，以及编程工作流的转变。正式编辑评论将把这些串成一条主线，而非简单罗列。",
  cuts,
};

await writeFile(
  join(DST, "claude-summaries.json"),
  JSON.stringify(cs, null, 2),
);

console.log(
  `[preview-data] wrote .preview-data/ with ${cuts.length} demo Editor's Cut entries`,
);
